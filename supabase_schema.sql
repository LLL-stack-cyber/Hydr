-- Run this in your Supabase SQL Editor to create the required table

CREATE TABLE IF NOT EXISTS public.sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id TEXT NOT NULL,
    ph NUMERIC,
    tds NUMERIC,
    turbidity NUMERIC,
    temperature NUMERIC,
    flow_in NUMERIC,
    flow_out NUMERIC,
    raw_tank_level NUMERIC,
    clean_tank_level NUMERIC,
    timestamp TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS) if you want to secure public access.
-- Note: The Service Role Key used by the backend will automatically bypass RLS.
ALTER TABLE public.sensor_readings ENABLE ROW LEVEL SECURITY;
